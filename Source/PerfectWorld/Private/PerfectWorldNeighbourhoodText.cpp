double NsTextWidth(const char* Text, double Px)
{
    const int32 N = NsLength(Text);
    return N <= 0 ? 0.0 : (N * NsGlyphPitch - 1) * Px;
}

bool NsCanDraw(const char* Text)
{
    for (int32 I = 0, N = NsLength(Text); I < N; ++I)
    {
        if (NsFindGlyph(Text[I]) == nullptr)
        {
            return false;
        }
    }
    return true;
}

int32 NsDrawText(FNsSink& K, const FLaneFrame& F, ELaneColour Colour, double U0, double WTop, double Px, double V0, double V1,
                 const char* Text)
{
    int32 Boxes = 0;
    for (int32 I = 0, N = NsLength(Text); I < N; ++I)
    {
        const FNsGlyph* Glyph = NsFindGlyph(Text[I]);
        if (Glyph == nullptr)
        {
            continue;
        }
        const double CellU = U0 + static_cast<double>(I * NsGlyphPitch) * Px;
        for (int32 Row = 0; Row < NsGlyphRows; ++Row)
        {
            const char* Line = Glyph->Rows[Row];
            int32 Col = 0;
            while (Col < NsGlyphCols)
            {
                if (Line[Col] != '#')
                {
                    ++Col;
                    continue;
                }
                int32 End = Col;
                while (End < NsGlyphCols && Line[End] == '#')
                {
                    ++End;
                }
                K.Add(F, Colour, CellU + Col * Px, CellU + End * Px, V0, V1, WTop - (Row + 1) * Px, WTop - Row * Px);
                ++Boxes;
                Col = End;
            }
        }
    }
    return Boxes;
}

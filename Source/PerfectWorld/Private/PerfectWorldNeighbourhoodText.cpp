const FNsGlyph* NsFindGlyph(char C)
{
    if (C >= 'a' && C <= 'z')
    {
        C = static_cast<char>(C - 'a' + 'A');
    }
    for (const FNsGlyph& G : NsGlyphs)
    {
        if (G.Character == C)
        {
            return &G;
        }
    }
    return nullptr;
}

int32 NsLength(const char* Text)
{
    int32 N = 0;
    while (Text != nullptr && Text[N] != '\0')
    {
        ++N;
    }
    return N;
}
